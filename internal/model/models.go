package model

import (
	"time"

	"gorm.io/gorm"
)

const (
	RoleAdmin       = "admin"
	StatusDraft     = "draft"
	StatusPublished = "published"
)

type User struct {
	ID           uint      `gorm:"primaryKey" json:"-"`
	Name         string    `gorm:"size:100;not null" json:"-"`
	Email        string    `gorm:"size:191;not null;uniqueIndex" json:"-"`
	PasswordHash string    `gorm:"size:255;not null" json:"-"`
	Avatar       string    `gorm:"size:500" json:"-"`
	Bio          string    `gorm:"type:text" json:"-"`
	Role         string    `gorm:"size:20;not null;default:admin;index" json:"-"`
	CreatedAt    time.Time `json:"-"`
	UpdatedAt    time.Time `json:"-"`
}

type Category struct {
	ID          uint      `gorm:"primaryKey" json:"-"`
	Name        string    `gorm:"size:100;not null" json:"-"`
	Slug        string    `gorm:"size:191;not null;uniqueIndex" json:"-"`
	Description string    `gorm:"type:text" json:"-"`
	CreatedAt   time.Time `json:"-"`
	UpdatedAt   time.Time `json:"-"`
}

type Tag struct {
	ID        uint      `gorm:"primaryKey" json:"-"`
	Name      string    `gorm:"size:100;not null" json:"-"`
	Slug      string    `gorm:"size:191;not null;uniqueIndex" json:"-"`
	CreatedAt time.Time `json:"-"`
	UpdatedAt time.Time `json:"-"`
}

type Post struct {
	ID          uint           `gorm:"primaryKey" json:"-"`
	Title       string         `gorm:"size:255;not null" json:"-"`
	Slug        string         `gorm:"size:191;not null;uniqueIndex" json:"-"`
	Excerpt     string         `gorm:"type:text" json:"-"`
	ContentMD   string         `gorm:"type:longtext;not null" json:"-"`
	ContentHTML string         `gorm:"type:longtext;not null" json:"-"`
	CoverImage  string         `gorm:"size:500" json:"-"`
	Status      string         `gorm:"size:20;not null;default:draft;index:idx_posts_status_published,priority:1" json:"-"`
	PublishedAt *time.Time     `gorm:"index:idx_posts_status_published,priority:2" json:"-"`
	AuthorID    uint           `gorm:"not null;index" json:"-"`
	Author      User           `gorm:"foreignKey:AuthorID;constraint:OnUpdate:CASCADE,OnDelete:RESTRICT" json:"-"`
	CategoryID  *uint          `gorm:"index" json:"-"`
	Category    *Category      `gorm:"foreignKey:CategoryID;constraint:OnUpdate:CASCADE,OnDelete:SET NULL" json:"-"`
	Tags        []Tag          `gorm:"many2many:post_tags;joinForeignKey:PostID;joinReferences:TagID" json:"-"`
	DeletedAt   gorm.DeletedAt `gorm:"index" json:"-"`
	CreatedAt   time.Time      `gorm:"index" json:"-"`
	UpdatedAt   time.Time      `json:"-"`
}

// SiteSetting stores the small set of public site preferences a blog author
// can change without a redeploy. A single row is expected; readers only ever
// receive the DTO below.
type SiteSetting struct {
	ID              uint      `gorm:"primaryKey" json:"-"`
	SiteName        string    `gorm:"size:100;not null" json:"-"`
	SiteTagline     string    `gorm:"size:200;not null" json:"-"`
	SiteDescription string    `gorm:"type:text" json:"-"`
	FooterText      string    `gorm:"size:255" json:"-"`
	ContactEmail    string    `gorm:"size:191" json:"-"`
	CreatedAt       time.Time `json:"-"`
	UpdatedAt       time.Time `json:"-"`
}

// Media is an uploaded file. StoredName is generated by the server and is the
// only value ever used to build a filesystem path.
type Media struct {
	ID           uint      `gorm:"primaryKey" json:"-"`
	OriginalName string    `gorm:"size:255;not null" json:"-"`
	StoredName   string    `gorm:"size:191;not null;uniqueIndex" json:"-"`
	MimeType     string    `gorm:"size:191;not null" json:"-"`
	Size         int64     `gorm:"not null" json:"-"`
	UploaderID   uint      `gorm:"index" json:"-"`
	CreatedAt    time.Time `gorm:"index" json:"-"`
}

// Comment is a public article comment. Email and QQ are never serialized to
// anonymous readers; only an avatar URL derived from the QQ number is exposed.
type Comment struct {
	ID        uint      `gorm:"primaryKey" json:"-"`
	PostID    uint      `gorm:"not null;index" json:"-"`
	ParentID  *uint     `gorm:"index" json:"-"`
	RootID    *uint     `gorm:"index" json:"-"`
	Nickname  string    `gorm:"size:60;not null" json:"-"`
	Email     string    `gorm:"size:191;not null" json:"-"`
	QQ        string    `gorm:"size:20" json:"-"`
	Content   string    `gorm:"type:text;not null" json:"-"`
	CreatedAt time.Time `gorm:"index" json:"-"`
}

type PostTag struct {
	PostID    uint      `gorm:"primaryKey" json:"-"`
	TagID     uint      `gorm:"primaryKey;index" json:"-"`
	CreatedAt time.Time `json:"-"`
}

func (PostTag) TableName() string {
	return "post_tags"
}
